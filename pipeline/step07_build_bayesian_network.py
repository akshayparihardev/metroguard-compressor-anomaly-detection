"""Step 7: learn a Bayesian network on fit windows, run the syllabus demos, explain alerts."""

import argparse
import json

import numpy as np
import pandas as pd

from metroguard import bayesian_network as bn
from metroguard import plotting
from metroguard.chronological_split import CALIB, FIT_SPLITS
from metroguard.config_loader import load_config
from metroguard.event_evaluation import (
    best_primary_model,
    evaluate_scored_model,
    events_to_explain,
    scored_models,
    test_alert_events,
)
from metroguard.step_run_tracking import (
    config_fingerprint,
    configure_step_logging,
    is_step_up_to_date,
    track_step_run,
)

STEP_NAME = "step07_build_bayesian_network"
STATES_FILE = "window_discrete_states.parquet"
FEATURES_FILE = "window_features.parquet"
BIN_EDGES_FILE = "discretisation_bin_edges.json"
UNUSUAL_SHARE_FACTOR = 2
SCORE_FILES = (
    "zscore_baseline_scores.parquet",
    "rbm_scores.parquet",
    "vae_scores.parquet",
    "markov_scores.parquet",
)


def state_counts(nodes: list[str], bin_edges: dict[str, list[float]]) -> dict[str, int]:
    """Number of states per node: bins for analog features, 2 for binarised digital ones."""
    return {n: len(bin_edges[n]) + 1 if n in bin_edges else 2 for n in nodes}


def demonstrations_markdown(model, data, edges) -> str:
    """Causal-direction query, evidential query, d-separation checks and local independencies."""
    (parent, child), mutual_information = bn.strongest_edge(model, data)
    lines = [
        "# Bayesian network demonstrations (generated by step 7)",
        "",
        "Edges are learned statistical dependencies, not causes. Terms follow the syllabus.",
        "",
        f"Learned edges ({len(edges)}): " + ", ".join(f"{a} -> {b}" for a, b in edges),
        "",
        f"Demonstration edge: `{parent} -> {child}` (highest empirical mutual information on fit "
        f"windows, {mutual_information:.3f} nats).",
        "",
        f"## Causal-direction query: P({child} | {parent} = state)",
        "",
        bn.conditional_table(model, child, parent).round(4).to_markdown(),
        "",
        f"## Evidential query: P({parent} | {child} = state)",
        "",
        bn.conditional_table(model, parent, child).round(4).to_markdown(),
        "",
        "## Local independence (node vs parents, non-parents, descendants)",
        "",
    ]
    cases = bn.local_independence_cases(model)
    if not cases:
        lines.append(
            "No node in this DAG has a parent, a descendant and a non-parent non-descendant."
        )
    for case in cases:
        given = ", ".join(case["given"]) or "nothing"
        relation = "dependent (d-connected)" if case["d_connected"] else "independent (d-separated)"
        lines.append(f"- {case['case']}: {case['pair'][0]} and {case['pair'][1]}, given {given}: "
                     f"**{relation}**")  # fmt: skip
    lines += ["", "## d-separation in chain, fork and collider patterns", ""]
    patterns = bn.structure_patterns(model)
    for p in patterns:
        a, b = p["ends"]
        lines.append(
            f"- {p['kind']} {a} / {p['middle']} / {b}: connected without evidence = "
            f"{p['connected_without_evidence']}; connected given {p['middle']} = "
            f"{p['connected_given_middle']}"
        )
    if not patterns:
        lines.append("No chain, fork or collider among non-adjacent nodes in this DAG.")
    return "\n".join(lines) + "\n"


def alert_context_markdown(model, states, table, calib_rows, explained, context_percentile) -> str:
    """Per-variable unusualness of the observed states during selected alert events."""
    lines = [
        "# Bayesian network alert context (generated by step 7)",
        "",
        "Per variable: -log P(observed state | Markov blanket) in nats, averaged over the "
        "windows of the alert event, against the same quantity on `calib` windows. Higher = "
        "the observed state is more unusual given its blanket. This describes association, "
        "not cause. A variable is marked unusual when the share of event windows above the calib "
        f"percentile exceeds {UNUSUAL_SHARE_FACTOR:g} times the share expected by chance.",
        "",
    ]
    chance_share = UNUSUAL_SHARE_FACTOR * (1 - context_percentile / 100)
    calib = {v: bn.blanket_surprisal(model, states[calib_rows], v) for v in states.columns}
    for event_id, event in explained:
        rows = (
            (table["window_start"] >= event["start"])
            & (table["window_start"] < event["end"])
            & table["usable"]
        ).to_numpy()
        lines += [
            f"## Reported window {event_id}: alert event {event['start']} to {event['end']} "
            f"({int(rows.sum())} usable windows)",
            "",
        ]
        records = []
        for variable in states.columns:
            observed = bn.blanket_surprisal(model, states[rows], variable)
            high = np.percentile(calib[variable], context_percentile)
            records.append(
                {
                    "variable": variable,
                    "event_mean": observed.mean(),
                    "calib_mean": calib[variable].mean(),
                    f"calib_p{context_percentile:g}": high,
                    f"share_above_calib_p{context_percentile:g}": (observed > high).mean(),
                    "unusual": "yes" if (observed > high).mean() > chance_share else "no",
                }
            )
        frame = pd.DataFrame(records).assign(gap=lambda f: f["event_mean"] - f["calib_mean"])
        frame = frame.sort_values("gap", ascending=False).drop(columns="gap")
        lines += [frame.round(4).to_markdown(index=False), ""]
    return "\n".join(lines)


def main() -> None:
    """Learn the BN, write demos and alert context, draw the DAG."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="recompute even if up to date")
    args = parser.parse_args()

    config = load_config()
    paths, sections = config.paths, config.sections
    bn_config = sections["bayesian_network"]
    log = configure_step_logging(STEP_NAME, paths.logs_dir)
    inputs = [paths.processed_dir / STATES_FILE, paths.processed_dir / FEATURES_FILE,
              paths.models_dir / BIN_EDGES_FILE, paths.tables_dir / "thresholds.json",
              *[paths.scores_dir / f for f in SCORE_FILES]]  # fmt: skip
    outputs = [
        paths.tables_dir / "bayesian_network_edges.csv",
        paths.tables_dir / "bayesian_network_demonstrations.md",
        paths.tables_dir / "bayesian_network_alert_context.md",
        paths.figures_dir / "bayesian_network" / "bayesian_network_dag.png",
    ]
    fingerprint = config_fingerprint(
        {k: sections[k] for k in ("seed", "split", "windows", "alerts", "evaluation",
                                  "thresholds", "bayesian_network")}
    )  # fmt: skip
    if not args.force and is_step_up_to_date(
        STEP_NAME, paths.logs_dir, inputs, outputs, fingerprint
    ):
        log.info("%s is up to date; use --force to recompute", STEP_NAME)
        return

    with track_step_run(STEP_NAME, paths.logs_dir, fingerprint):
        nodes = bn_config["nodes"]
        table = pd.read_parquet(inputs[1], columns=["window_start", "split", "usable"])
        states = pd.read_parquet(inputs[0])
        bin_edges = json.loads(inputs[2].read_text())
        node_states = bn.categorical_node_table(states, nodes, state_counts(nodes, bin_edges))
        usable = table["usable"].to_numpy()
        fit_rows = table["split"].isin(FIT_SPLITS).to_numpy() & usable
        calib_rows = (table["split"] == CALIB).to_numpy() & usable
        log.info("BN nodes %d; fit windows %d; calib windows %d", len(nodes), fit_rows.sum(),
                 calib_rows.sum())  # fmt: skip

        fit_data = node_states[fit_rows]
        edges = bn.learn_structure(fit_data, bn_config["scoring_method"], bn_config["max_indegree"])
        model = bn.fit_cpds(edges, fit_data, bn_config["equivalent_sample_size"])
        log.info("Learned %d edges: %s", len(edges), edges)

        paths.tables_dir.mkdir(parents=True, exist_ok=True)
        pd.DataFrame(edges, columns=["parent", "child"]).to_csv(outputs[0], index=False)
        outputs[1].write_text(demonstrations_markdown(model, fit_data, edges), encoding="utf-8")
        plotting.plot_bayesian_network_dag(edges, nodes, outputs[3])

        window_seconds = sections["windows"]["size_seconds"]
        thresholds = json.loads(inputs[3].read_text())
        rows = []
        models = scored_models(paths.scores_dir, sections["rbm"]["k_values"])
        primary_percentile = sections["thresholds"]["primary_percentile"]
        for scored in models:
            if scored.is_primary:
                limits = {str(primary_percentile): thresholds[scored.model][scored.score][
                    "thresholds"][f"{primary_percentile:g}"]}  # fmt: skip
                rows += evaluate_scored_model(
                    scored, limits, window_seconds, sections["alerts"]["merge_gap_minutes"],
                    sections["alerts"]["min_event_windows"],
                    sections["evaluation"]["lead_tolerance_hours"],
                )  # fmt: skip
        best = best_primary_model(rows, float(primary_percentile))
        best_scored = next(
            m for m in models if (m.model, m.score) == (best["model"], best["score"])
        )
        events = test_alert_events(
            best_scored,
            best["threshold"],
            window_seconds,
            sections["alerts"]["merge_gap_minutes"],
            sections["alerts"]["min_event_windows"],
        )
        explained = events_to_explain(events, bn_config["context_events"])
        log.info("Best model for context: %s (%s), %d of 4 events detected; explaining %s",
                 best["model"], best["score"], best["events_detected"],
                 [e for e, _ in explained])  # fmt: skip
        context = alert_context_markdown(
            model, node_states, table, calib_rows, explained, bn_config["context_percentile"]
        )
        header = (f"Model used: `{best['model']}` ({best['score']}, {primary_percentile:g}th "
                  f"percentile threshold). Chosen as the primary-score model detecting the most "
                  f"reported events on test (ties: fewest unconfirmed alerts/day). This choice "
                  f"does not change any threshold or model.\n\n")  # fmt: skip
        first_break = context.index("\n\n") + 2
        outputs[2].write_text(context[:first_break] + header + context[first_break:],
                              encoding="utf-8")  # fmt: skip
        log.info("Wrote %s", [p.name for p in outputs])


if __name__ == "__main__":
    main()
