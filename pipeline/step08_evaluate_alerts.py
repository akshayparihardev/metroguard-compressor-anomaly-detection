"""Step 8: evaluate alert events against the reported failure windows, on test windows only."""

import argparse
import json
import os
from datetime import datetime

import pandas as pd

from metroguard import artifact_names as artifacts
from metroguard.alerting.event_evaluation import evaluate_scored_model, scored_models
from metroguard.config_loader import load_config
from metroguard.data.chronological_split import TEST
from metroguard.data.failure_windows import REPORTED_FAILURE_WINDOWS
from metroguard.reporting import plotting
from metroguard.step_run_tracking import (
    config_fingerprint,
    configure_step_logging,
    is_step_up_to_date,
    track_step_run,
)

STEP_NAME = "step08_evaluate_alerts"
TABLE_COLUMNS = [
    "model",
    "score",
    "percentile",
    "threshold",
    "n_alert_windows",
    "alert_window_fraction",
    "n_alert_events",
    "events_detected",
    "detected_event_ids",
    "unconfirmed_alert_events",
    "unconfirmed_alerts_per_day",
]
DELAY_COLUMNS = [f"delay_hours_event{w.event_id}" for w in REPORTED_FAILURE_WINDOWS]
EVENT_ZOOM_AFTER_HOURS = 12


def metrics_markdown(
    metrics: pd.DataFrame, thresholds: dict, scores_dir, primary: float, lead_hours: float
) -> str:
    """Human-readable metrics tables built only from the saved metrics rows."""
    main = metrics[metrics["is_primary_score"] & (metrics["percentile"] == primary)]
    sensitivity = metrics[metrics["is_primary_score"]].sort_values(["model", "percentile"])
    secondary = metrics[~metrics["is_primary_score"] & (metrics["percentile"] == primary)]
    frozen = [
        {"model": m, "score": s, "frozen_at": e["frozen_at"], "calib_windows": e["n_calib_windows"]}
        for m, scores in sorted(thresholds.items())
        for s, e in sorted(scores.items())
    ]
    modified = {
        f: datetime.fromtimestamp(os.path.getmtime(scores_dir / f)).isoformat(timespec="seconds")
        for f in artifacts.SCORE_FILES
    }
    first = metrics.iloc[0]
    range_days = sum(
        (w.end - (w.start - pd.Timedelta(hours=lead_hours))) / pd.Timedelta(days=1)
        for w in REPORTED_FAILURE_WINDOWS
    )
    range_share = range_days / first["test_days"]
    lines = [
        "# Event-level metrics (generated by step 8)",
        "",
        "All metrics use usable test windows only "
        f"({int(first['n_usable_test_windows']):,} windows, "
        f"{first['test_days']:.1f} calendar days). "
        "Thresholds were fitted on calib and frozen before each model scored test. Alerts "
        "outside reported windows are **unconfirmed alerts**, "
        "not false alarms. Detection range = [start - 24 h, end]; delay = first alert time in that "
        "range minus window start (negative = before the reported start). With only four reported "
        "events these results are exploratory.",
        "",
        f"## Primary scores at the {primary:g}th percentile threshold",
        "",
        main[TABLE_COLUMNS].to_markdown(index=False, floatfmt=".4g"),
        "",
        f"**How to read detection.** The four detection ranges ([start - {lead_hours:g} h, end]) "
        f"together cover {range_days:.1f} of the {first['test_days']:.1f} test days "
        f"({100 * range_share:.1f}%). A model that flags a large share of all windows will overlap "
        "these ranges by chance, so 'events detected' must be read together with "
        "'alert_window_fraction' and 'unconfirmed_alerts_per_day'. A delay near "
        f"-{lead_hours:g} h means an alert event was already running when the lead range began "
        "(the delay is clipped to the range start), not that the failure was anticipated.",
        "",
        "Detection delay in hours (nan = not detected):",
        "",
        main[["model", *DELAY_COLUMNS]].to_markdown(index=False, floatfmt=".2f"),
        "",
        "## Threshold sensitivity (primary scores, 99th vs 99.5th percentile)",
        "",
        sensitivity[TABLE_COLUMNS].to_markdown(index=False, floatfmt=".4g"),
        "",
        "## Secondary scores",
        "",
        secondary[TABLE_COLUMNS].to_markdown(index=False, floatfmt=".4g"),
        "",
        "## Evidence that thresholds were frozen before test scoring",
        "",
        pd.DataFrame(frozen).to_markdown(index=False),
        "",
        "Score-table file modification times (written after thresholds were frozen):",
        "",
        pd.DataFrame(
            {"file": list(modified), "last_modified": list(modified.values())}
        ).to_markdown(index=False),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    """Compute metrics for every model and score, write tables and figures."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--force", action="store_true", help="recompute even if up to date")
    args = parser.parse_args()

    config = load_config()
    paths, sections = config.paths, config.sections
    log = configure_step_logging(STEP_NAME, paths.logs_dir)
    thresholds_path = paths.tables_dir / artifacts.THRESHOLDS_FILE
    figures_dir = paths.figures_dir / "evaluation"
    outputs = [
        paths.tables_dir / artifacts.METRICS_CSV_FILE,
        paths.tables_dir / artifacts.METRICS_MD_FILE,
    ]
    inputs = [thresholds_path, *[paths.scores_dir / f for f in artifacts.SCORE_FILES]]
    fingerprint = config_fingerprint(
        {
            k: sections[k]
            for k in ("seed", "split", "windows", "alerts", "evaluation", "thresholds", "rbm")
        }
    )
    if not args.force and is_step_up_to_date(
        STEP_NAME, paths.logs_dir, inputs, outputs, fingerprint
    ):
        log.info("%s is up to date; use --force to recompute", STEP_NAME)
        return

    with track_step_run(STEP_NAME, paths.logs_dir, fingerprint):
        thresholds = json.loads(thresholds_path.read_text())
        models = scored_models(paths.scores_dir, sections["rbm"]["k_values"])
        window_seconds = sections["windows"]["size_seconds"]
        lead_hours = sections["evaluation"]["lead_tolerance_hours"]
        rows = []
        for scored in models:
            entry = thresholds[scored.model][scored.score]["thresholds"]
            rows += evaluate_scored_model(
                scored,
                entry,
                window_seconds,
                sections["alerts"]["merge_gap_minutes"],
                sections["alerts"]["min_event_windows"],
                lead_hours,
            )
        metrics = pd.DataFrame(rows)
        metrics.to_csv(outputs[0], index=False)
        primary = float(sections["thresholds"]["primary_percentile"])
        outputs[1].write_text(
            metrics_markdown(metrics, thresholds, paths.scores_dir, primary, lead_hours),
            encoding="utf-8",
        )

        first_test = min(m.window_starts[(m.split == TEST).to_numpy()].min() for m in models)
        train_end = first_test.normalize().replace(day=1)
        primary_models = [m for m in models if m.is_primary]
        panels = []
        for scored in primary_models:
            limit = thresholds[scored.model][scored.score]["thresholds"][f"{primary:g}"]
            plotting.plot_score_vs_time(
                scored.window_starts,
                scored.scores,
                scored.usable,
                limit,
                scored.score,
                f"{scored.model}: {scored.score} over time",
                train_end,
                figures_dir / f"{scored.model}_score_vs_time.png",
            )
            panels.append(
                {
                    "name": scored.model,
                    "score": scored.score,
                    "window_starts": scored.window_starts,
                    "scores": scored.scores,
                    "usable": scored.usable,
                    "threshold": limit,
                }
            )
        for window in REPORTED_FAILURE_WINDOWS:
            plotting.plot_event_zoom_scores(
                window,
                panels,
                lead_hours,
                EVENT_ZOOM_AFTER_HOURS,
                figures_dir / f"event{window.event_id}_zoom_scores_all_models.png",
            )
        rbm_rows = metrics[
            metrics["model"].str.startswith("rbm_k") & (metrics["percentile"] == primary)
        ]
        plotting.plot_cd_k_comparison(
            rbm_rows.assign(k=rbm_rows["model"].str.removeprefix("rbm_k").astype(int)),
            figures_dir / "rbm_cd_k_comparison.png",
        )
        summary = metrics[metrics["is_primary_score"] & (metrics["percentile"] == primary)]
        shown = ["model", "events_detected", "alert_window_fraction", "unconfirmed_alerts_per_day"]
        log.info(
            "Primary scores at p%g:\n%s", primary, summary[shown].round(3).to_string(index=False)
        )
        n_figures = len(primary_models) + len(REPORTED_FAILURE_WINDOWS) + 1
        log.info(
            "Wrote %s, %s and %d figures in %s", outputs[0], outputs[1], n_figures, figures_dir
        )


if __name__ == "__main__":
    main()
